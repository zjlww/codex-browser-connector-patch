def clone_file(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    try:
        subprocess.run(
            ["cp", "-c", src, dst],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except Exception:
        shutil.copy2(src, dst)


# --- asar integrity ---------------------------------------------------------
#
# Electron refuses to load an entry whose bytes no longer match the SHA-256 the
# asar JSON header recorded for it, and refuses the archive outright when the
# header itself no longer matches Info.plist. Editing `canServeSession()` inside
# app.asar therefore has to rewrite both, or the app exits seconds after launch
# with "ASAR Integrity Violation: got a hash mismatch".


def asar_header_span(mm):
    """Return (json_start, json_size) for a mapped asar file."""
    json_start = mm.find(b'{"files":')
    if json_start < 4:
        raise ValueError("no asar JSON header found")
    json_size = int.from_bytes(mm[json_start - 4 : json_start], "little")
    if json_size <= 0 or json_start + json_size > len(mm):
        raise ValueError("asar JSON header is out of range")
    return json_start, json_size


def asar_entry_at(header, content_offset):
    """Return the header node that owns content_offset, or None."""
    stack = [header]
    while stack:
        node = stack.pop()
        for value in node.get("files", {}).values():
            if "files" in value:
                stack.append(value)
            elif "offset" in value:
                start = int(value["offset"])
                if start <= content_offset < start + value["size"]:
                    return value
    return None


def hash_region(mm, offset, size, block_size=None):
    """SHA-256 of a mapped region, plus per-block hashes when block_size is set."""
    digest = hashlib.sha256()
    mm.seek(offset)
    remaining = size
    while remaining > 0:
        chunk = mm.read(min(1 << 20, remaining))
        if not chunk:
            raise ValueError("short read at %d" % offset)
        digest.update(chunk)
        remaining -= len(chunk)
    blocks = None
    if block_size:
        blocks = []
        for start in range(offset, offset + size, block_size):
            block = hashlib.sha256()
            mm.seek(start)
            remaining = min(block_size, offset + size - start)
            while remaining > 0:
                chunk = mm.read(min(1 << 20, remaining))
                if not chunk:
                    raise ValueError("short read at %d" % start)
                block.update(chunk)
                remaining -= len(chunk)
            blocks.append(block.hexdigest())
    return digest.hexdigest(), blocks


def info_plist_asar_hash():
    with open(INFO_PLIST, "rb") as fh:
        plist = plistlib.load(fh)
    return plist["ElectronAsarIntegrity"][INFO_PLIST_ASAR_KEY]["hash"]


def set_info_plist_asar_hash(new_hash):
    """Point ElectronAsarIntegrity at a rewritten header, touching nothing else."""
    with open(INFO_PLIST, "rb") as fh:
        body = fh.read()
    old_hash = info_plist_asar_hash()
    if old_hash == new_hash:
        return
    if len(new_hash) == len(old_hash) and body.count(old_hash.encode()) == 1:
        body = body.replace(old_hash.encode(), new_hash.encode())
    else:
        # Not a unique literal: fall back to a structural rewrite.
        plist = plistlib.loads(body)
        plist["ElectronAsarIntegrity"][INFO_PLIST_ASAR_KEY]["hash"] = new_hash
        body = plistlib.dumps(plist, fmt=plistlib.FMT_XML)
    tmp = INFO_PLIST + ".tmp-patch"
    with open(tmp, "wb") as fh:
        fh.write(body)
    with open(tmp, "rb") as fh:
        plistlib.load(fh)  # never install a plist we cannot parse back
    shutil.copymode(INFO_PLIST, tmp)
    os.replace(tmp, INFO_PLIST)
    print("updated ElectronAsarIntegrity hash in %s" % INFO_PLIST)


def framework_binary():
    """Path of the Electron framework that carries the packaged digest."""
    if os.path.exists(FRAMEWORK_CURRENT):
        return FRAMEWORK_CURRENT
    matches = sorted(glob.glob(FRAMEWORK_GLOB))
    return matches[-1] if matches else None


def integrity_dictionary_digest(dictionary):
    """Reproduce Electron's IsIntegrityDictionaryValid() digest.

    integrity_digest.mm walks the dictionary's keys in literal sort order and
    absorbs the UTF-8 bytes of the key, the algorithm and the hash of each
    entry, with no separators or length prefixes.
    """
    hasher = hashlib.sha256()
    for key in sorted(dictionary):
        entry = dictionary[key]
        hasher.update(key.encode("utf-8"))
        hasher.update(str(entry.get("algorithm", "")).encode("utf-8"))
        hasher.update(str(entry.get("hash", "")).encode("utf-8"))
    return hasher.digest()


def current_integrity_digest():
    with open(INFO_PLIST, "rb") as fh:
        plist = plistlib.load(fh)
    return integrity_dictionary_digest(plist["ElectronAsarIntegrity"])


def find_integrity_slots(path):
    """Locate the __asar_integrity digest slots WITHOUT mapping the file.

    The framework must never be mmapped once its signature is stale: macOS
    kills any process that maps one of its pages ("CODESIGNING, Code 2 Invalid
    Page"). Plain read()/write() through a file descriptor is safe.

    Returns [(file_offset, used, version, digest_bytes)].
    """
    slots = []
    keep = INTEGRITY_SLOT_SIZE - 1
    with open(path, "rb") as fh:
        carry = b""
        buf_start = 0
        while True:
            chunk = fh.read(1 << 20)
            if not chunk and not carry:
                break
            buf = carry + chunk
            at = 0
            while True:
                at = buf.find(INTEGRITY_SENTINEL, at)
                if at < 0:
                    break
                if at + INTEGRITY_SLOT_SIZE <= len(buf):
                    slot = buf[at : at + INTEGRITY_SLOT_SIZE]
                    slots.append((buf_start + at, slot[32], slot[33], slot[34:66]))
                at += 1
            carry = buf[-keep:]
            buf_start += len(buf) - len(carry)
            if not chunk:
                break
    return slots


def framework_integrity_status():
    """ok | stale | missing | unknown.

    `stale` is the state that makes Electron 41+ log
    "Failed to get integrity for validatable asar archive" and exit.
    """
    path = framework_binary()
    if path is None or not os.path.exists(path):
        return "missing"
    try:
        expected = current_integrity_digest()
        slots = find_integrity_slots(path)
        if not slots:
            return "missing"
        stale = False
        for _offset, used, version, digest in slots:
            if used == 0:  # used == false: Electron fails open
                continue
            if version != 1:
                return "unknown"
            if digest != expected:
                stale = True
        return "stale" if stale else "ok"
    except Exception:
        return "unknown"


def patch_framework_integrity():
    path = framework_binary()
    if path is None:
        sys.exit("could not find the Codex Framework binary under %s" % APP)
    if not os.path.exists(FRAMEWORK_BACKUP):
        clone_file(path, FRAMEWORK_BACKUP)
        print(
            "backed up -> %s (%s)"
            % (FRAMEWORK_BACKUP, sha256(FRAMEWORK_BACKUP)[:16])
        )
    expected = current_integrity_digest()
    slots = find_integrity_slots(path)
    if not slots:
        sys.exit("no __asar_integrity digest slot found in %s" % path)
    changed = 0
    with open(path, "r+b") as fh:
        for offset, used, version, digest in slots:
            if used == 0:
                continue
            if version != 1:
                sys.exit(
                    "unsupported __asar_integrity digest version %d in %s"
                    % (version, path)
                )
            if digest != expected:
                fh.seek(offset + 34)
                fh.write(expected)
                changed += 1
        fh.flush()
        os.fsync(fh.fileno())
    print(
        "updated asar integrity dictionary digest in %s (%d slot(s))"
        % (path, changed)
    )
    return changed


def rehash_asar_entry(path, patched_offset):
    """Re-hash the asar entry covering patched_offset and rewrite the header.

    Returns the SHA-256 of the new header, which is what Info.plist must carry,
    or None when the offset does not fall inside a known entry.
    """
    with open(path, "r+b") as fh:
        with mmap.mmap(fh.fileno(), 0) as mm:
            json_start, json_size = asar_header_span(mm)
            base = json_start + json_size
            header = json.loads(mm[json_start : json_start + json_size])
            entry = asar_entry_at(header, patched_offset - base)
            if entry is None or "integrity" not in entry:
                return None
            digest, blocks = hash_region(
                mm,
                base + int(entry["offset"]),
                entry["size"],
                entry["integrity"].get("blockSize"),
            )
            entry["integrity"]["hash"] = digest
            if blocks is not None:
                entry["integrity"]["blocks"] = blocks
            new_header = json.dumps(
                header, separators=(",", ":"), ensure_ascii=False
            ).encode("utf-8")
            if len(new_header) != json_size:
                raise ValueError(
                    "asar header length changed (%d -> %d); refusing to rewrite"
                    % (json_size, len(new_header))
                )
            mm.seek(json_start)
            mm.write(new_header)
            mm.flush()
            return hashlib.sha256(new_header).hexdigest()


def host_route_status():
    if not os.path.exists(HOST_ASAR):
        return "missing"
    try:
        with open(HOST_ASAR, "rb") as fh:
            with mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ) as mm:
                if mm.find(HOST_MARKER_V2) >= 0:
                    marker, current = mm.find(HOST_MARKER_V2), True
                elif mm.find(HOST_MARKER) >= 0:
                    marker, current = mm.find(HOST_MARKER), False
                elif mm.find(HOST_START) >= 0:
                    return "unpatched"
                else:
                    return "unknown"
                json_start, json_size = asar_header_span(mm)
                base = json_start + json_size
                header = json.loads(mm[json_start : json_start + json_size])
                entry = asar_entry_at(header, marker - base)
                if entry is None or "integrity" not in entry:
                    return "unknown"
                digest, blocks = hash_region(
                    mm,
                    base + int(entry["offset"]),
                    entry["size"],
                    entry["integrity"].get("blockSize"),
                )
                if digest != entry["integrity"]["hash"]:
                    return "integrity-broken"
                if blocks is not None and blocks != entry["integrity"].get("blocks"):
                    return "integrity-broken"
                header_hash = hashlib.sha256(
                    mm[json_start : json_start + json_size]
                ).hexdigest()
                try:
                    expected = info_plist_asar_hash()
                except Exception:
                    return "unknown"
                if header_hash != expected:
                    return "header-integrity-broken"
                if framework_integrity_status() == "stale":
                    return "dictionary-digest-stale"
                return "patched" if current else "outdated"
    except Exception:
        return "unknown"


def repair_host_integrity():
    """Re-derive all three guard hashes for an already-spliced host route.

    Reachable after a partial or older patch: the route bytes are in the asar
    but one of the integrity guards describes the previous contents, which is
    exactly the state that stops the app booting.
    """
    with open(HOST_ASAR, "rb") as fh:
        with mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ) as mm:
            marker = mm.find(HOST_MARKER_V2)
            if marker < 0:
                marker = mm.find(HOST_MARKER)
    if marker < 0:
        sys.exit("no host route marker in %s; restore instead" % HOST_ASAR)
    new_header_hash = rehash_asar_entry(HOST_ASAR, marker)
    if new_header_hash is None:
        sys.exit("could not find the asar entry covering the host route")
    set_info_plist_asar_hash(new_header_hash)
    patch_framework_integrity()
    print(
        "repaired host route integrity: %s (header sha256 %s)"
        % (HOST_ASAR, new_header_hash[:16])
    )


